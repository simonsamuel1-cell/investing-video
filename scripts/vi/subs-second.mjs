// subs-second.mjs — a second subtitle language, cue for cue with an episode's burned-in Indonesian (subtitles.ts):
// the same start/end, the text from a translation file (docs/subtitles/tr/<KEY>.json, rows [{i, <lang>}]).
//   node scripts/vi/subs-second.mjs src/episodes/<ep> docs/subtitles/tr/VI02.json zh
// Writes src/episodes/<ep>/subtitles-<lang>.ts (export CUES_<LANG>). Re-run after every VO revision; it stops if the
// Indonesian cue count no longer matches the translation's rows (a re-cut line needs re-translating, not shifting).
import fs from "node:fs";
const [ep, trPath, lang] = process.argv.slice(2);
const src = fs.readFileSync(`${ep}/subtitles.ts`, "utf8");
const re = /\{\s*start:\s*(\d+),\s*end:\s*(\d+),\s*text:\s*"((?:[^"\\]|\\.)*)"\s*\}/g;
const cues = [...src.matchAll(re)].map((m) => ({ start: +m[1], end: +m[2] }));
const rows = JSON.parse(fs.readFileSync(trPath, "utf8")).rows;
if (rows.length !== cues.length) throw new Error(`${cues.length} Indonesian cues, ${rows.length} translated rows`);
const L = lang.toUpperCase();
const body = cues.map((q, i) => `  { start: ${q.start}, end: ${q.end}, text: ${JSON.stringify(rows[i][lang])} },`).join("\n");
fs.writeFileSync(
  `${ep}/subtitles-${lang}.ts`,
  `/**\n * subtitles-${lang}.ts — the second subtitle line (${lang}), cue for cue with subtitles.ts.\n *\n * GENERATED by scripts/vi/subs-second.mjs from ${trPath}. Do not edit by hand — fix the translation and regenerate.\n */\nimport type { Cue } from "../../core";\n\nexport const CUES_${L}: Cue[] = [\n${body}\n];\n`,
);
console.log(`${cues.length} ${lang} cues -> ${ep}/subtitles-${lang}.ts`);
