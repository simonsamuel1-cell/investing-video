#!/usr/bin/env python3
"""
ref-library.py — builds the Pustaka Referensi page (every style reference Simon has sent) from
docs/vi-style/refs/library.json into a folder that the Artifact tool publishes as-is:

  python3 scripts/vi/ref-library.py [out/ref-library]

  out/ref-library/index.html     the page (scripts/vi/ref-library.html with the library inlined)
  out/ref-library/m/<id>.webp    each image, ≤ 2000 px
  out/ref-library/m/<id>.mp4     each video, ≤ 960 px on its long side, no sound
  out/ref-library/m/<id>-t.webp  the card thumbnail (a video's is a frame at 30 %)
  out/ref-library/files.json     the m/ paths, for the publish call's `files`

Media already built and newer than its source is kept, so adding one reference only encodes that one.

  python3 scripts/vi/ref-library.py out/ref-library --skill ~/.claude/skills/tuntun-remotion-episode

also writes the references into that skill, so another account gets them with the zip:
<skill>/references/benchmarks/<id>.webp (a still, or a video as 8 frames on one sheet) and INDEX.md.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIB = ROOT / "docs/vi-style/refs/library.json"
TEMPLATE = Path(__file__).with_name("ref-library.html")
FULL, THUMB, VIDEO = 2000, 720, 960


def probe(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height",
                          "-show_entries", "format=duration", "-of", "json", str(path)], capture_output=True, check=True, text=True).stdout
    j = json.loads(out)
    s = j["streams"][0]
    return s["width"], s["height"], float(j.get("format", {}).get("duration") or 0)


def fresh(dst, src):
    return dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime


def webp(src, dst, longest):
    if fresh(dst, src):
        return
    w, h, _ = probe(src)
    size = ["-resize", str(min(w, longest)), "0"] if w >= h else ["-resize", "0", str(min(h, longest))]
    if src.suffix.lower() not in (".png", ".jpg", ".jpeg", ".webp"):
        raise SystemExit(f"{src}: not an image cwebp reads")
    subprocess.run(["cwebp", "-quiet", "-q", "82", *size, str(src), "-o", str(dst)], check=True)


def video(src, dst, poster):
    w, h, dur = probe(src)
    if not fresh(dst, src):
        k = min(1, VIDEO / max(w, h))
        vw, vh = int(w * k) // 2 * 2, int(h * k) // 2 * 2
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-vf", f"scale={vw}:{vh}", "-c:v", "libx264", "-preset", "slow",
                        "-crf", "30", "-pix_fmt", "yuv420p", "-an", "-movflags", "+faststart", str(dst)], check=True)
    if not fresh(poster, src):
        png = poster.with_suffix(".png")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", f"{dur * 0.3:.2f}", "-i", str(src), "-frames:v", "1", str(png)], check=True)
        webp(png, poster, THUMB)
        png.unlink()
    return w, h, dur


def sheet(src, dst, dur, w, h, n=8):
    """n frames spread evenly over the video, 4 per row — what a skill can look at instead of a video."""
    if fresh(dst, src):
        return
    cell = "480:-2" if w >= h else "-2:480"
    png = dst.with_suffix(".png")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-vf", f"fps={n}/{dur:.3f},scale={cell},tile=4x{n // 4}:padding=6:color=white",
                    "-frames:v", "1", str(png)], check=True)
    subprocess.run(["cwebp", "-quiet", "-q", "72", str(png), "-o", str(dst)], check=True)
    png.unlink()


def to_skill(lib, out, skill):
    """Each reference as one picture in <skill>/references/benchmarks/, plus INDEX.md saying what it teaches."""
    bdir = skill / "references/benchmarks"
    bdir.mkdir(parents=True, exist_ok=True)
    keep = {"INDEX.md"}
    lines = ["# Benchmarks — every style reference Simon has sent, as pictures",
             "",
             "Generated by `scripts/vi/ref-library.py --skill` from `docs/vi-style/refs/library.json`. Don't edit by hand.",
             "Open a file with the Read tool to look at it. A video is shown as 8 frames spread evenly over its length,",
             "read left to right and top to bottom. What each collection teaches in words is in `../vi-style.md`.",
             ""]
    for c in lib["collections"]:
        lines += [f"## {c['date']} · {c['title']} — {c['statusLabel']}", ""]
        if c.get("quote"):
            lines += [f"> Simon: \"{c['quote']}\"", ""]
        for k, label in (("taken", "Taken"), ("dropped", "Dropped"), ("open", "Still open"), ("usedIn", "Used in")):
            if c.get(k):
                lines.append(f"- **{label}:** " + "; ".join(c[k]))
        lines.append("")
        for it in c["items"]:
            name = f"{it['id']}.webp"
            if it["type"] == "video":
                sheet(out / it["media"], bdir / name, it["dur"], it["w"], it["h"])
                kind = f"video, {it['dur']:.0f} s, 8 frames"
            elif it.get("media"):
                src = out / it["media"]
                if not fresh(bdir / name, src):
                    (bdir / name).write_bytes(src.read_bytes())
                kind = "contact sheet of the video" if it["type"] == "link" else "image"
            else:
                name, kind = None, "link only"
            if name:
                keep.add(name)
            ref = f"[`{name}`]({name})" if name else "—"
            src = f" · [source]({it['url']})" if it.get("url") else ""
            lines.append(f"- {ref} **{it['title']}** ({kind}){src} — {it['note']}")
        lines.append("")
    (bdir / "INDEX.md").write_text("\n".join(lines))
    for f in bdir.iterdir():
        if f.name not in keep:
            f.unlink()
    mb = sum(f.stat().st_size for f in bdir.iterdir()) / 1e6
    print(f"{len(keep) - 1} benchmark pictures, {mb:.1f} MB -> {bdir}")


def main():
    args = sys.argv[1:]
    skill = None
    if "--skill" in args:
        i = args.index("--skill")
        skill = Path(args[i + 1]).expanduser().resolve()
        del args[i : i + 2]
    out = Path(args[0] if args else ROOT / "out/ref-library").resolve()
    (out / "m").mkdir(parents=True, exist_ok=True)
    lib = json.loads(LIB.read_text())
    files = []
    for col in lib["collections"]:
        for it in col["items"]:
            src = Path(it["src"]) if it.get("src") else None
            src = src if src is None or src.is_absolute() else ROOT / src
            thumb = Path(it["thumb"]) if it.get("thumb") else None
            thumb = thumb if thumb is None or thumb.is_absolute() else ROOT / thumb
            iid = it["id"]
            if it["type"] == "image":
                webp(src, out / f"m/{iid}.webp", FULL)
                webp(src, out / f"m/{iid}-t.webp", THUMB)
                w, h, _ = probe(src)
                it.update(media=f"m/{iid}.webp", thumbUrl=f"m/{iid}-t.webp", w=w, h=h)
            elif it["type"] == "video":
                w, h, dur = video(src, out / f"m/{iid}.mp4", out / f"m/{iid}-t.webp")
                it.update(media=f"m/{iid}.mp4", thumbUrl=f"m/{iid}-t.webp", w=w, h=h, dur=round(dur, 1))
            elif thumb:
                webp(thumb, out / f"m/{iid}.webp", FULL)
                webp(thumb, out / f"m/{iid}-t.webp", THUMB)
                w, h, _ = probe(thumb)
                it.update(media=f"m/{iid}.webp", thumbUrl=f"m/{iid}-t.webp", w=w, h=h)
            # where the original lives, shown on the page so a reference can be found again on disk
            if src:
                it["path"] = str(src.relative_to(ROOT)) if src.is_relative_to(ROOT) else str(src).replace(str(Path.home()) + "/Documents/", "")
            files += [it[k] for k in ("media", "thumbUrl") if it.get(k)]
            it.pop("src", None), it.pop("thumb", None)
    lib.pop("_", None)
    data = json.dumps(lib, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    (out / "index.html").write_text(TEMPLATE.read_text().replace("/*LIBRARY*/null", data))
    (out / "files.json").write_text(json.dumps([{"path": f} for f in files], indent=0))
    mb = sum((out / f).stat().st_size for f in files) / 1e6
    print(f"{len(files)} media files, {mb:.1f} MB -> {out}")
    if skill:
        to_skill(lib, out, skill)


if __name__ == "__main__":
    main()
